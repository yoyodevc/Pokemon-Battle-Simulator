import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
const { chromium } = await import(pathToFileURL(process.argv[2]).href);
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const base = 'http://localhost:5174';
const a = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const b = await browser.newContext({ viewport: { width: 390, height: 844 } });
const post = async (context, path, data = {}) => {
  const response = await context.request.post(`${base}/api/league/${path}`, { data });
  assert.equal(response.ok(), true, await response.text());
  return response.json();
};
try {
  await post(a, 'guest');
  const rival = await post(b, 'guest');
  const invite = await post(a, 'challenge', { target: rival.user.id });
  const p = await a.newPage(), q = await b.newPage();
  const errors = [];
  for (const page of [p, q]) page.on('pageerror', e => errors.push(e.message));
  await q.goto(`${base}/#league`);
  await q.locator('.lg-challenge-card').waitFor();
  await q.screenshot({ path: '.league/challenge-mobile.png', fullPage: true });
  await q.locator('.lg-challenge-card').getByRole('button', { name: 'Accept duel' }).click();
  await q.getByRole('heading', { name: 'Choose your six.' }).waitFor();
  const id = q.url().split('#match/')[1];
  assert.ok(invite.id && id);
  await p.goto(`${base}/#match/${id}`);
  await p.getByLabel('Team name', { exact: true }).fill('Test composition');
  await p.getByRole('button', { name: 'Save composition' }).click();
  await p.reload();
  await p.getByRole('button', { name: 'Use team', exact: true }).click();
  assert.equal(await p.locator('.lg-saved-team').count(), 1);
  await p.getByRole('button', { name: 'Lock team & ready up' }).click();
  await q.getByRole('button', { name: 'Lock team & ready up' }).click();
  await p.locator('.battle-move').first().waitFor({ timeout: 180000 });
  await q.locator('.battle-move').first().waitFor({ timeout: 180000 });
  await p.locator('.battle-move').first().click();
  await q.locator('.battle-move').first().click();
  await p.locator('.hud-turn strong').filter({ hasText: '01' }).waitFor();
  const state = await post(a, 'match', { id });
  await post(a, 'action', { id, version: state.version, action: { kind: 'forfeit' } });
  await p.goto(`${base}/#league`);
  await p.getByRole('button', { name: 'Battle history', exact: true }).click();
  await p.getByRole('button', { name: /Watch replay/ }).click();
  await p.getByRole('button', { name: 'Play replay' }).click();
  await p.waitForFunction(() => Number(document.querySelector('[aria-label="Replay position"]').value) > 0);
  await p.getByRole('button', { name: 'Pause replay' }).click();
  assert.equal(await p.getByRole('button', { name: 'Next event', exact: true }).count(), 0);
  assert.equal(await p.getByLabel('Jump to turn').count(), 0);
  assert.equal(await p.locator('.battle-dialogue .eyebrow').textContent(), 'TURN RESOLUTION');
  assert.equal(await p.locator('.lg-turn-event[aria-current="step"]').count(), 1);
  await p.locator('.lg-turn-event').last().click();
  assert.equal(await p.getByLabel('Replay position').inputValue(), String(await p.locator('.lg-turn-event').count() - 1));
  assert.equal(await p.locator('.battle-dialogue .dialogue-text').textContent(), await p.locator('.lg-turn-event[aria-current="step"] strong').textContent());
  await p.getByLabel('Replay position').fill('0');
  await p.screenshot({ path: '.league/replay-desktop.png', fullPage: true });
  assert.equal(await q.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.deepEqual(errors, []);
  console.log('PASS: incoming challenge, acceptance, saved-team reload/use, real battle, history replay, play/pause/scrub, no browser exceptions.');
} finally { await browser.close(); }
