import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
const { default: { chromium } } = await import(pathToFileURL(process.argv[2]).href);
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const base = process.env.LEAGUE_TEST_URL || 'http://localhost:5174';
const first = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const second = await browser.newContext({ viewport: { width: 390, height: 844 } });
const a = await first.newPage(), b = await second.newPage();
const errors = [];
for (const page of [a, b]) page.on('pageerror', error => errors.push(error.message));
try {
  await a.goto(`${base}/#league`);
  await a.getByRole('button', { name: 'Play as Guest' }).click();
  await a.getByRole('button', { name: 'Create duel invitation' }).waitFor();
  await a.getByRole('button', { name: 'Trainer profile', exact: true }).click();
  await a.getByLabel('Trainer name', { exact: true }).fill(`QA_${Date.now()}`);
  await a.getByRole('button', { name: 'Save profile', exact: true }).click();
  await a.getByText('Trainer profile saved.', { exact: true }).waitFor();
  await a.getByRole('button', { name: 'Overview', exact: true }).click();
  await a.screenshot({ path: '.league/desktop-lobby.png', fullPage: true });
  await a.getByRole('button', { name: 'Create duel invitation' }).click();
  const link = await a.getByLabel('Invitation link').inputValue();
  await b.goto(link);
  await b.getByRole('button', { name: 'Play as Guest' }).click();
  await b.getByRole('button', { name: 'Accept duel' }).click();
  await b.getByRole('heading', { name: 'Choose your six.' }).waitFor();
  await a.getByRole('button', { name: 'Return to match' }).click();
  await a.getByRole('heading', { name: 'Choose your six.' }).waitFor();
  await b.screenshot({ path: '.league/mobile-room.png', fullPage: true });
  await a.getByRole('button', { name: 'Lock team & ready up' }).click();
  await b.getByRole('button', { name: 'Lock team & ready up' }).click();
  await a.locator('.battle-move').first().waitFor({ timeout: 180000 });
  await b.locator('.battle-move').first().waitFor({ timeout: 180000 });
  assert.equal(await a.locator('main main').count(), 0);
  assert.equal(await b.locator('.combatant-0 img').getAttribute('src'), await a.locator('.combatant-0 img').getAttribute('src'));
  await a.locator('.battle-move').first().click();
  await b.locator('.battle-move').first().click();
  await a.locator('.hud-turn strong').filter({ hasText: '01' }).waitFor();
  await b.reload();
  await b.locator('.hud-turn strong').filter({ hasText: '01' }).waitFor();
  await a.evaluate(() => window.scrollTo(0, 0));
  await b.evaluate(() => window.scrollTo(0, 0));
  await a.screenshot({ path: '.league/desktop-battle.png', fullPage: true });
  await b.screenshot({ path: '.league/mobile-battle.png', fullPage: true });
  const overflow = await b.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  assert.equal(overflow, false, 'mobile page must not overflow');
  await a.getByRole('button', { name: 'Run', exact: true }).click();
  await a.keyboard.press('Escape');
  assert.equal(await a.getByRole('dialog').count(), 0);
  await a.getByRole('button', { name: 'Run', exact: true }).click();
  await a.getByRole('button', { name: 'Forfeit', exact: true }).click();
  await b.locator('.result-banner.is-victory').waitFor();
  await a.getByRole('button', { name: /^Rematch/ }).click();
  await b.getByRole('button', { name: /^Rematch/ }).click();
  await a.getByRole('heading', { name: 'Choose your six.' }).waitFor();
  await b.getByRole('heading', { name: 'Choose your six.' }).waitFor();
  await a.getByRole('button', { name: 'Leave room', exact: true }).click();
  await a.getByRole('dialog').getByRole('button', { name: 'Leave room', exact: true }).click();
  await a.getByRole('heading', { name: 'Room closed' }).waitFor();
  assert.deepEqual(errors, []);
  console.log('PASS: independent guest sessions, invitation, teams, authoritative turn, refresh/reconnect, forfeit, history, mutual rematch, mobile overflow, no browser exceptions.');
} finally { await browser.close(); }
